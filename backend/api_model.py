"""Базовая модель ответа API.

В базе время хранится наивным UTC — так его кладёт `datetime.utcnow()` во
всех умолчаниях, и на этом же держатся все сравнения в коде. Проблема не в
хранении, а в границе: наружу такое время уходило строкой без пометки о
поясе, а стандарт разрешает клиенту считать её местной. Браузер так и делал.

Для врача в Душанбе это было пять часов ошибки в каждой дате приложения:
запись, сделанная в 14:30, показывалась как 09:30. То же читает приложение
пациента — там время визита уезжало на те же пять часов.

Здесь ставится пометка `Z`. Значения в питоне остаются наивными, поэтому ни
одно сравнение — включая проверки истечения токенов — не меняется.
"""
from datetime import datetime, timezone

from pydantic import BaseModel, field_serializer


class ApiModel(BaseModel):
    """Модель ответа, у которой время всегда уходит с часовым поясом."""

    # when_used="json" обязательно: без него поправка попадала бы и в
    # model_dump(), а его результат кладут в колонки базы — SQLAlchemy
    # получал строку вместо datetime и падал на записи.
    @field_serializer("*", when_used="json")
    def _utc_marker(self, v, _info):
        # Осведомлённое время не трогаем: если когда-нибудь колонки станут
        # timezone-aware, поправка не должна сработать вторым слоем.
        if isinstance(v, datetime) and v.tzinfo is None:
            return v.replace(tzinfo=timezone.utc).isoformat().replace("+00:00", "Z")
        return v
